"""Close workpaper: one workbook an auditor or controller can tick and tie."""
from __future__ import annotations

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

F = "Arial"
HDR = PatternFill("solid", fgColor="1F3864")
SUB = PatternFill("solid", fgColor="D9E1F2")
MONEY = '$#,##0.00;($#,##0.00);"-"'
INT = '#,##0;(#,##0);"-"'
thin = Side(style="thin", color="BFBFBF")


def _hdr(ws, row, headers, widths=None):
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=j, value=h)
        c.font = Font(name=F, bold=True, color="FFFFFF", size=10)
        c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical="center")
    if widths:
        for j, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(j)].width = w
    ws.freeze_panes = ws.cell(row=row + 1, column=1)


def _title(ws, t, sub=None):
    ws["A1"] = t
    ws["A1"].font = Font(name=F, bold=True, size=14, color="1F3864")
    if sub:
        ws["A2"] = sub
        ws["A2"].font = Font(name=F, italic=True, size=9, color="595959")


def _font_all(wb):
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                if c.value is not None and (c.font is None or c.font.name != F):
                    c.font = Font(name=F, size=c.font.size or 10, bold=c.font.bold, italic=c.font.italic, color=c.font.color)


def build_workbook(path, bundle, detail, store, months):
    s = bundle["summary"]
    wb = Workbook()

    # ------------------------------------------------------------ Exceptions (clusters)
    wx = wb.active
    wx.title = "Exceptions"
    _title(wx, "Open exception clusters", "One row per root cause. Explanations generated by the AI investigator from engine facts (grounding-checked).")
    cols = ["Root cause", "Status", "Member-months", "Members", "Expected", "Paid", "Variance (after retro alloc.)", "Owner", "Recommended action", "Accounting treatment", "Explanation", "Explanation method"]
    _hdr(wx, 4, cols, [38, 10, 13, 10, 15, 15, 17, 18, 40, 32, 90, 24])
    r = 5
    for c in bundle["clusters"]:
        vals = [c["label"], c["status"], c["member_months"], c["members"], c["expected_usd"], c["paid_usd"], c["variance_usd"],
                c["owner"], c["recommended_action"], c["accounting_treatment"], c["explanation"], c["explanation_method"]]
        for j, v in enumerate(vals, 1):
            cell = wx.cell(row=r, column=j, value=v)
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            if j in (5, 6, 7):
                cell.number_format = MONEY
            if j in (3, 4):
                cell.number_format = INT
        r += 1
    last_ex = r - 1
    wx.cell(row=r, column=1, value="Total open").font = Font(name=F, bold=True)
    for j in (3, 5, 6, 7):
        col = get_column_letter(j)
        cell = wx.cell(row=r, column=j, value=f"=SUM({col}5:{col}{last_ex})")
        cell.number_format = MONEY if j > 4 else INT
        cell.font = Font(name=F, bold=True)
    ex_total_row = r

    # ------------------------------------------------------------ Cash
    wc = wb.create_sheet("Cash Recon")
    _title(wc, "820 remittance vs bank deposits", "Bank: operating acct 4410023. Cut-off = month end.")
    _hdr(wc, 4, ["820 trace", "Pay date", "820 total (BPR)", "Deposit date", "Deposit", "Difference", "Match method", "Status"], [18, 12, 16, 12, 16, 14, 20, 14])
    r = 5
    for c in bundle["cash"]:
        wc.cell(row=r, column=1, value=c["trace"])
        wc.cell(row=r, column=2, value=str(c["pay_date"])[:10])
        wc.cell(row=r, column=3, value=c["remit_total"]).number_format = MONEY
        wc.cell(row=r, column=4, value=str(c["deposit_date"])[:10] if c["deposit_date"] else "")
        wc.cell(row=r, column=5, value=c["deposit"]).number_format = MONEY
        wc.cell(row=r, column=6, value=f"=E{r}-C{r}").number_format = MONEY
        wc.cell(row=r, column=7, value=c["match_method"])
        wc.cell(row=r, column=8, value=c["status"])
        r += 1
    cash_last = r - 1
    wc.cell(row=r, column=1, value="Total").font = Font(name=F, bold=True)
    for j in (3, 5, 6):
        col = get_column_letter(j)
        wc.cell(row=r, column=j, value=f"=SUM({col}5:{col}{cash_last})").number_format = MONEY
    cash_tot = r
    r += 2
    wc.cell(row=r, column=1, value="Reconciling items & explanations").font = Font(name=F, bold=True)
    r += 1
    for it in bundle["cash_items"]:
        wc.cell(row=r, column=1, value=it["item"])
        wc.cell(row=r, column=2, value=it["status"])
        wc.cell(row=r, column=3, value=it["amount"]).number_format = MONEY
        wc.cell(row=r, column=4, value=it["explanation"]).alignment = Alignment(wrap_text=True)
        wc.merge_cells(start_row=r, start_column=4, end_row=r, end_column=8)
        wc.row_dimensions[r].height = 48
        r += 1

    # ------------------------------------------------------------ Retro triangle
    wt = wb.create_sheet("Retro Triangle")
    _title(wt, "Prior-period development: expected revenue by coverage month (rows) as recognised at each close (columns)",
           "Diagonal = originally booked. Cells right of the diagonal = prior-period adjustments caused by new rate versions.")
    _hdr(wt, 4, ["Coverage month"] + [f"{m} close" for m in months] + ["Total (= current view)"], [16] + [14] * (len(months) + 1))
    r = 5
    for row in bundle["triangle"]:
        wt.cell(row=r, column=1, value=row["coverage_month"])
        for j, m in enumerate(months, 2):
            v = row.get(m)
            cell = wt.cell(row=r, column=j, value=v)
            cell.number_format = MONEY
            if v and row["coverage_month"] < m and abs(v) > 0.005:
                cell.fill = PatternFill("solid", fgColor="FCE4D6")
        tc = wt.cell(row=r, column=len(months) + 2, value=f"=SUM(B{r}:{get_column_letter(len(months) + 1)}{r})")
        tc.number_format = MONEY
        tc.font = Font(name=F, bold=True)
        r += 1
    wt.cell(row=r, column=1, value="Recognised in close").font = Font(name=F, bold=True)
    for j in range(2, len(months) + 3):
        col = get_column_letter(j)
        wt.cell(row=r, column=j, value=f"=SUM({col}5:{col}{r - 1})").number_format = MONEY
    tri_tot = r
    r += 2
    wt.cell(row=r, column=1, value="Attribution").font = Font(name=F, bold=True)
    for a in bundle["ppa"]:
        r += 1
        wt.cell(row=r, column=1, value=f"{a['close']} close")
        wt.cell(row=r, column=2, value=a["prior_period_adjustment"]).number_format = MONEY
        wt.cell(row=r, column=3, value=a["versions"])

    # ------------------------------------------------------------ Retro settlements & withhold
    wr = wb.create_sheet("Retro & Withhold")
    _title(wr, "Aggregate retro settlements (re-performed) and quality withhold check")
    _hdr(wr, 4, ["820 trace", "Description", "Rate version", "Lump sum paid", "Re-performed on state basis", "Residual", "Member-months allocated", "Months"], [18, 34, 14, 16, 20, 12, 16, 18])
    r = 5
    for l in bundle["lumps"]:
        for j, v in enumerate([l["trace"], l["desc"], l["version"], l["amount"], l["state_basis_estimate"], None, l["member_months"], l["months"]], 1):
            wr.cell(row=r, column=j, value=v)
        wr.cell(row=r, column=6, value=f"=D{r}-E{r}")
        for j in (4, 5, 6):
            wr.cell(row=r, column=j).number_format = MONEY
        r += 1
    r += 2
    _hdr(wr, r, ["Period", "820 trace", "Gross current capitation", "Withheld (820)", "Contract 1.0%", "Difference", "Status"])
    wr.freeze_panes = None
    r0 = r + 1
    for w in bundle["withhold"]:
        r += 1
        for j, v in enumerate([w["period"], w["trace"], w["gross_current"], w["withheld"], None, None, w["status"]], 1):
            wr.cell(row=r, column=j, value=v)
        wr.cell(row=r, column=5, value=f"=-ROUND(C{r}*$B${r0 + len(bundle['withhold'])},2)")
        wr.cell(row=r, column=6, value=f"=D{r}-E{r}")
        for j in (3, 4, 5, 6):
            wr.cell(row=r, column=j).number_format = MONEY
    r += 1
    wr.cell(row=r, column=1, value="Withhold % (contract)")
    wr.cell(row=r, column=2, value=0.01).number_format = "0.0%"
    wr.cell(row=r, column=2).font = Font(name=F, color="0000FF")
    wr.cell(row=r, column=3, value="Input: contract quality-withhold percentage").font = Font(name=F, italic=True, size=9)
    wr.cell(row=r + 1, column=1, value="Withhold receivable YTD")
    wr.cell(row=r + 1, column=4, value=f"=-SUM(D{r0}:D{r - 1})").number_format = MONEY

    # ------------------------------------------------------------ Roll-forward
    wf = wb.create_sheet("Roll-forward")
    _title(wf, "Exception roll-forward by close (member-month items, $ = paid - expected)")
    heads = ["Close", "Opening #", "Opening $", "New #", "New $", "Resolved #", "Resolved $", "Re-measured $", "Closing #", "Closing $", "Check"]
    _hdr(wf, 4, heads, [10, 11, 15, 9, 15, 11, 15, 14, 10, 15, 10])
    r = 5
    for x in bundle["rollforward"]:
        vals = [x["close"], x["opening_items"], x["opening_usd"], x["new_items"], x["new_usd"], x["resolved_items"], x["resolved_usd"], x["changed_usd"], x["closing_items"], x["closing_usd"]]
        for j, v in enumerate(vals, 1):
            c = wf.cell(row=r, column=j, value=v)
            c.number_format = MONEY if j in (3, 5, 7, 8, 10) else INT
        wf.cell(row=r, column=11, value=f'=IF(ABS(C{r}+E{r}-G{r}+H{r}-J{r})<0.05,"ties","CHECK")')
        r += 1

    # ------------------------------------------------------------ Journal
    wj = wb.create_sheet("Draft JEs")
    _title(wj, f"Draft journal entries - {s['month']} close (for controller review; not posted)",
           "Reserve/liability entries shown as required ending balances; post the difference vs. current GL balance.")
    _hdr(wj, 4, ["Entry", "Description", "Debit", "Credit", "Amount", "Basis"], [7, 70, 32, 34, 16, 34])
    r = 5
    for e in bundle["journal"]:
        for j, v in enumerate([e["entry"], e["description"], e["debit"], e["credit"], e["amount"], e["basis"]], 1):
            wj.cell(row=r, column=j, value=v).alignment = Alignment(wrap_text=True, vertical="top")
        wj.cell(row=r, column=5).number_format = MONEY
        r += 1

    # ------------------------------------------------------------ Rate history
    wh = wb.create_sheet("Rate History")
    _title(wh, "Approved rate versions (bitemporal store) and resulting PMPM by cell and month")
    _hdr(wh, 4, ["Version", "Source document", "Type", "Effective", "Recorded (approved) at", "Approved by", "Extraction method", "Retro"], [13, 42, 18, 18, 20, 32, 30, 8])
    r = 5
    for v in bundle["rate_versions"]:
        for j, k in enumerate(["version_id", "source_doc", "change_type", "effective", "recorded_at", "approved_by", "method", "retroactive"], 1):
            wh.cell(row=r, column=j, value=str(v[k]))
        r += 1
    r += 2
    hdr_row = r
    _hdr(wh, r, ["Cell"] + months)
    wh.freeze_panes = None
    for cell in sorted({c for v in store.versions for c, _ in v.materialized}):
        r += 1
        wh.cell(row=r, column=1, value=cell)
        for j, m in enumerate(months, 2):
            rate, vid = store.lookup(cell, m)
            c = wh.cell(row=r, column=j, value=rate)
            c.number_format = MONEY
            if vid == "RV-2026-003":
                c.fill = PatternFill("solid", fgColor="FCE4D6")
            elif vid == "RV-2026-002":
                c.fill = PatternFill("solid", fgColor="E2EFDA")
    wh.cell(row=r + 2, column=1, value="Green = Amendment 1 (RV-2026-002); orange = Amendment 2 retro (RV-2026-003)").font = Font(name=F, italic=True, size=9)

    # ------------------------------------------------------------ Rate intake
    wi = wb.create_sheet("Rate Intake")
    _title(wi, "Rate intake approval packets", "Extraction -> validation checks -> impact preview -> human sign-off")
    r = 4
    for p in bundle["proposals"]:
        wi.cell(row=r, column=1, value=f"{p['version_id']}  {p['source_doc']}").font = Font(name=F, bold=True, size=11, color="1F3864")
        r += 1
        meta = [("Format", p["doc_type"]), ("Extraction", p["extraction_method"]), ("Change type", p["change_type"]),
                ("Effective", f"{p['effective_from']} .. {p['effective_to']}"), ("Retroactive", p["retroactive"]),
                ("Confidence", p["confidence"]), ("State", p["state"]),
                ("Approved", f"{p['approval']['approved_by']} at {p['approval']['approved_at']}" if p["approval"] else "-")]
        if p["adjustment"]:
            meta.append(("Rule", f"{p['adjustment']['pct']:+.2%} on {p['adjustment']['regions']} categories={p['adjustment']['categories'] or 'ALL'} basis={p['adjustment']['basis']}"))
        if p.get("payment_method"):
            meta.append(("Payment", p["payment_method"]))
        for k, v in meta:
            wi.cell(row=r, column=1, value=k).font = Font(name=F, bold=True)
            wi.cell(row=r, column=2, value=str(v))
            r += 1
        for chk in p["checks"]:
            wi.cell(row=r, column=1, value="Check")
            wi.cell(row=r, column=2, value=chk["check"])
            c = wi.cell(row=r, column=3, value=chk["result"])
            c.fill = PatternFill("solid", fgColor={"pass": "E2EFDA", "WARN": "FFF2CC", "FAIL": "F8CBAD"}[chk["result"]])
            wi.cell(row=r, column=4, value=chk["detail"])
            r += 1
        for q in p["open_questions"]:
            wi.cell(row=r, column=1, value="Question")
            wi.cell(row=r, column=2, value=q)
            r += 1
        for cte in p["citations"]:
            wi.cell(row=r, column=1, value="Citation")
            wi.cell(row=r, column=2, value=cte["field"])
            wi.cell(row=r, column=4, value=cte["quote"])
            r += 1
        if p["impact"]:
            wi.cell(row=r, column=1, value="Impact").font = Font(name=F, bold=True)
            wi.cell(row=r, column=2, value="$ vs. rates on file, by coverage month")
            r += 1
            for mo, amt in p["impact"].items():
                wi.cell(row=r, column=2, value=mo)
                wi.cell(row=r, column=3, value=amt).number_format = MONEY
                r += 1
        r += 1
    wi.column_dimensions["A"].width = 14
    wi.column_dimensions["B"].width = 48
    wi.column_dimensions["C"].width = 14
    wi.column_dimensions["D"].width = 90

    # ------------------------------------------------------------ Detail
    wd = wb.create_sheet("Exception Detail")
    _title(wd, "Open / pending member-month exceptions")
    cols = ["member_id", "cov_month", "cell", "paid_cell", "expected", "paid", "aggregate_alloc", "variance_after", "code", "label", "status", "traces"]
    _hdr(wd, 4, cols, [12, 10, 10, 10, 12, 12, 13, 13, 22, 40, 9, 30])
    ex = detail[detail.status.isin(["open", "pending"])].sort_values(["code", "member_id", "cov_month"])
    r = 5
    for row in ex[cols].itertuples(index=False):
        for j, v in enumerate(row, 1):
            c = wd.cell(row=r, column=j, value=None if v != v else v)
            if j in (5, 6, 7, 8):
                c.number_format = MONEY
        r += 1

    # ------------------------------------------------------------ Summary (first)
    ws = wb.create_sheet("Summary", 0)
    _title(ws, f"Capitation revenue reconciliation - {s['month']} close", f"Sunrise Health Plan (synthetic data). Close as of {s['close_as_of'][:10]}.")
    ws.column_dimensions["A"].width = 58
    ws.column_dimensions["B"].width = 20
    ws.column_dimensions["C"].width = 60
    rows = [
        ("Three-way reconciliation (YTD Jan - " + s["month"] + ")", None, None, True),
        ("A. Expected capitation (plan roster x approved rates)", s["expected_ytd"], "Engine: member-month expected revenue", False),
        ("B. Paid at member level on 820s", s["paid_ytd"], "Sum of 820 member lines by coverage month", False),
        ("C. Aggregate retro settlements (820 header RT)", s["lump_sums_ytd"], "See Retro & Withhold", False),
        ("D. Open variance  = B + C - A", "=B5+B6-B4", "Should equal open exceptions total", False),
        ("   Open exceptions per cluster sheet", f"=Exceptions!G{ex_total_row}", None, False),
        ("   Check", '=IF(ABS(B7-B8)<1,"ties","CHECK")', None, False),
        ("E. Quality withhold retained (820 header QW)", f"=-'Retro & Withhold'!D{r0 + len(bundle['withhold']) + 2}*-1", "Receivable pending quality results", False),
        ("F. Net remitted per 820s (BPR)", f"='Cash Recon'!C{cash_tot}", None, False),
        ("G. Deposits matched to 820s (incl. in transit at cut-off)", f"='Cash Recon'!E{cash_tot}", None, False),
        ("H. Remittance vs bank difference", "=B13-B12", "Explained on Cash Recon (short-pay, in transit)", False),
        ("Automation", None, None, True),
        ("Member-months reconciled", s["member_months"], None, False),
        ("Auto-matched or auto-resolved", s["auto_matched"], None, False),
        ("Auto-match rate", "=B17/B16", None, False),
        ("Raw member-month variances before root-cause clustering", s["raw_variance_items"], None, False),
        ("Open items / clusters for human review", f"{s['open_items']} items in {s['clusters']} clusters", None, False),
        ("Items with no root cause (unexplained)", s["unexplained_items"], None, False),
        ("Prior-period adjustments recognised YTD", f"=SUM('Retro Triangle'!C{tri_tot}:{get_column_letter(len(months) + 1)}{tri_tot})-SUMPRODUCT(('Retro Triangle'!A5:A{tri_tot - 1}='Retro Triangle'!A5:A{tri_tot - 1})*0)", "Off-diagonal cells of the triangle", False),
    ]
    r = 3
    for label, val, note, head in rows:
        r += 1 if not head or r == 3 else 2
        a = ws.cell(row=r, column=1, value=label)
        if head:
            a.font = Font(name=F, bold=True, color="FFFFFF")
            a.fill = HDR
            ws.cell(row=r, column=2).fill = HDR
            ws.cell(row=r, column=3).fill = HDR
            continue
        b = ws.cell(row=r, column=2, value=val)
        if isinstance(val, (int, float)) and not isinstance(val, bool) and label.startswith(("A", "B", "C", "E", "F", "G")):
            b.number_format = MONEY
        if note:
            ws.cell(row=r, column=3, value=note).font = Font(name=F, italic=True, size=9, color="595959")
    wb.save(path)
    _fix_summary(path, ex_total_row, cash_tot, tri_tot, months, r0, len(bundle["withhold"]))


def _fix_summary(path, ex_total_row, cash_tot, tri_tot, months, r0, nwh):
    """Rewrite summary cells with explicit addresses (keeps formulas readable)."""
    from openpyxl import load_workbook

    wb = load_workbook(path)
    ws = wb["Summary"]
    # locate rows by label
    pos = {ws.cell(row=i, column=1).value: i for i in range(1, ws.max_row + 1)}
    A = pos["A. Expected capitation (plan roster x approved rates)"]
    B = pos["B. Paid at member level on 820s"]
    C = pos["C. Aggregate retro settlements (820 header RT)"]
    D = pos["D. Open variance  = B + C - A"]
    E = pos["   Open exceptions per cluster sheet"]
    K = pos["   Check"]
    W = pos["E. Quality withhold retained (820 header QW)"]
    Fr = pos["F. Net remitted per 820s (BPR)"]
    G = pos["G. Deposits matched to 820s (incl. in transit at cut-off)"]
    H = pos["H. Remittance vs bank difference"]
    MM = pos["Member-months reconciled"]
    AM = pos["Auto-matched or auto-resolved"]
    AR = pos["Auto-match rate"]
    PP = pos["Prior-period adjustments recognised YTD"]
    money = '$#,##0.00;($#,##0.00);"-"'
    ws.cell(row=D, column=2, value=f"=B{B}+B{C}-B{A}").number_format = money
    ws.cell(row=E, column=2, value=f"=Exceptions!G{ex_total_row}").number_format = money
    ws.cell(row=K, column=2, value=f'=IF(ABS(B{D}-B{E})<1,"ties","CHECK")')
    ws.cell(row=W, column=2, value=f"='Retro & Withhold'!D{r0 + nwh + 1}").number_format = money
    ws.cell(row=Fr, column=2, value=f"='Cash Recon'!C{cash_tot}").number_format = money
    ws.cell(row=G, column=2, value=f"='Cash Recon'!E{cash_tot}").number_format = money
    ws.cell(row=H, column=2, value=f"=B{G}-B{Fr}").number_format = money
    ws.cell(row=MM, column=2).number_format = "#,##0"
    ws.cell(row=AM, column=2).number_format = "#,##0"
    ws.cell(row=pos["Raw member-month variances before root-cause clustering"], column=2).number_format = "#,##0"
    ws.cell(row=AR, column=2, value=f"=B{AM}/B{MM}").number_format = "0.00%"
    # triangle: total of everything recognised minus the diagonal = sum of off-diagonal; compute as total minus diagonal cells
    diag = "+".join(f"'Retro Triangle'!{get_column_letter(2 + i)}{5 + i}" for i in range(len(months)))
    ws.cell(row=PP, column=2, value=f"='Retro Triangle'!{get_column_letter(len(months) + 2)}{tri_tot}-({diag})").number_format = money
    for row in ws.iter_rows():
        for c in row:
            if c.value is not None:
                c.font = Font(name=F, size=c.font.size or 10, bold=c.font.bold, italic=c.font.italic, color=c.font.color)
    wb.save(path)
